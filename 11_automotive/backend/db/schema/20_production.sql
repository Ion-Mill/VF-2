-- 근거: 논리ERD 5.B, 6.7~6.9, R-05~R-08, R-13, R-19
-- bottleneck_log는 alarm_event 뒤(30), lot_hold는 tool 뒤(40)에 만든다.
-- 업무 번호 형식은 CHECK로 막는다 → 생성기 CSV 번호가 어긋나면 적재 때 바로 드러난다.
